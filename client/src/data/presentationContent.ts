export interface ProjectData {
  id: string;
  year: number;
  title: string;
  titleRu: string;
  location: string;
  locationRu: string;
  category: string;
  client: string;
  details: string;
  detailsRu: string;
  image: string;
  gallery: string[];
  scope: string[];
  scopeRu: string[];
  specs: { label: string; value: string }[];
  specsRu: { label: string; value: string }[];
}

export function getLocalizedProject(p: ProjectData, lang: 'en' | 'ru' | 'kk') {
  if (lang === 'ru') {
    return {
      ...p,
      title: p.titleRu || p.title,
      location: p.locationRu || p.location,
      details: p.detailsRu || p.details,
      scope: p.scopeRu || p.scope,
      specs: p.specsRu || p.specs,
    };
  }

  if (lang === 'kk') {
    return {
      ...p,
      title: p.title || p.titleRu,
      location: p.location || p.locationRu,
      details: p.details || p.detailsRu,
      scope: p.scope,
      specs: p.specs,
    };
  }

  return p;
}

